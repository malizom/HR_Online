// Generates the RLS migration body from the live schema list so no tenant table can be missed.
import fs from "node:fs";
const { getTableConfig } = await import("drizzle-orm/pg-core");
const schema = await import(new URL(process.argv[2], `file://${process.cwd()}/`).href);
const platform = new Set(schema.PLATFORM_TABLES);
const shared = new Set(schema.SHARED_ROW_TABLES);
const tables = Object.values(schema).filter(v => v && typeof v === "object" && Symbol.for("drizzle:IsDrizzleTable") in v)
  .map(t => getTableConfig(t).name).filter(n => !platform.has(n)).sort();
const cur = `nullif(current_setting('app.firm_id', true), '')::uuid`;
let out = `-- Row-level security for every tenant table (design doc 01 §3, doc 02 §1).\n-- Generated by scripts/gen-rls.mjs. FORCE applies the policy to the table owner too: fail closed.\n`;
for (const t of tables) {
  out += `--> statement-breakpoint\nALTER TABLE "${t}" ENABLE ROW LEVEL SECURITY;\n--> statement-breakpoint\nALTER TABLE "${t}" FORCE ROW LEVEL SECURITY;\n--> statement-breakpoint\n`;
  if (shared.has(t)) {
    out += `CREATE POLICY tenant_read ON "${t}" FOR SELECT USING (firm_id IS NULL OR firm_id = ${cur});\n--> statement-breakpoint\n`;
    out += `CREATE POLICY tenant_write ON "${t}" FOR ALL USING (firm_id = ${cur} OR (firm_id IS NULL AND current_setting('app.platform', true) = 'on')) WITH CHECK (firm_id = ${cur} OR (firm_id IS NULL AND current_setting('app.platform', true) = 'on'));\n`;
  } else {
    out += `CREATE POLICY tenant_isolation ON "${t}" USING (firm_id = ${cur}) WITH CHECK (firm_id = ${cur});\n`;
  }
}
fs.writeFileSync(process.argv[3], out);
console.log(`RLS for ${tables.length} tenant tables`);
